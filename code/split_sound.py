#!/usr/bin/env python3
"""split_sound.py NAME [PER=4000] [DIR=lean/Erdos634/Refl]

Splits DIR/M<NAME>Sound.lean, as written by rust/certgenm (one module with one theorem `sound<i>` per piece of the
certificate), into parts DIR/M<NAME>SoundP<j>.lean with at most PER theorems each, and a short DIR/M<NAME>Sound.lean
that keeps `not_dissection`.  Same declarations, same names, same namespace, same order: nothing downstream changes
(`import Erdos634.Refl.M<NAME>Sound` still gives `Refl.M<NAME>.not_dissection`, `TGT`, `MODEL`, `MODEL_sides`).

Reason: Lean 4.30 aborts with "Stack overflow detected" at the end of a module with 61,542 theorems
(S3N161, 37 MB, after 587 s); modules with 43,189 (ISO132) and 28,343 (S1N156) theorems are fine.  rust/certgenx writes
the parts itself; this script does the same for certificates generated by rust/certgenm.

Deterministic: the output depends only on the input file and PER.  The input file is replaced; it is regenerated by
code/regen_cert.sh (manifest rows with the 14th column `certgenm+split:<PER>` call this script).
"""
import io, os, sys

def main():
    name = sys.argv[1]
    per = int(sys.argv[2]) if len(sys.argv) > 2 else 4000
    d = sys.argv[3] if len(sys.argv) > 3 else os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'lean', 'Erdos634', 'Refl')
    src = os.path.join(d, 'M%sSound.lean' % name)
    L = io.open(src, encoding='utf-8').read().split('\n')
    ns = 'namespace Refl.M%s' % name
    i_ns = L.index(ns)
    assert L[i_ns + 1] == 'open Refl', L[i_ns + 1]
    imports = [l for l in L[:i_ns] if l.startswith('import ')]
    assert not any(l.startswith('import Erdos634.Refl.M%sSoundP' % name) for l in imports), 'already split'
    opens = [l for l in L[:i_ns] if l.startswith('open ')]
    assert len(opens) == 1, opens
    d0 = [k for k, l in enumerate(L[:i_ns]) if l.startswith('/-!')][0]
    d1 = [k for k, l in enumerate(L[:i_ns]) if l.rstrip().endswith('-/') and k >= d0][0]
    doc = L[d0:d1 + 1]
    starts = [k for k, l in enumerate(L) if l.startswith('theorem sound')]
    i_nd = [k for k, l in enumerate(L) if l.startswith('theorem not_dissection')]
    assert len(i_nd) == 1 and starts and starts[-1] < i_nd[0]
    i_nd = i_nd[0]
    pre = L[i_ns + 2:starts[0]]
    # nothing but theorems `sound<i>` between the first one and `not_dissection`
    body_end = i_nd
    while L[body_end - 1].strip() == '':
        body_end -= 1
    for k in range(starts[0], body_end):
        l = L[k]
        assert not (l[:1] not in (' ', '') and not l.startswith('theorem sound')), (k, l[:80])
    bounds = starts + [body_end]
    blocks = [L[bounds[k]:bounds[k + 1]] for k in range(len(starts))]
    tail = L[i_nd:]
    assert any(l == 'end Refl.M%s' % name for l in tail)
    nparts = (len(blocks) + per - 1) // per
    for j in range(nparts):
        out = []
        if j == 0:
            out += imports
        else:
            out.append('import Erdos634.Refl.M%sSoundP%d' % (name, j - 1))
        out.append('')
        out.append('/-! GENERATED by rust/certgenm, split by code/split_sound.py.  Soundness of the pieces of the certificate of '
                   'instance `%s` (part %d of %d). -/' % (name, j, nparts))
        out.append('')
        out += opens
        out.append('')
        out.append(ns)
        out.append('open Refl')
        out.append('')
        if j == 0:
            out += pre
        for b in blocks[j * per:(j + 1) * per]:
            out += b
        out.append('end Refl.M%s' % name)
        out.append('')
        io.open(os.path.join(d, 'M%sSoundP%d.lean' % (name, j)), 'w', encoding='utf-8').write('\n'.join(out))
    out = ['import Erdos634.Refl.M%sSoundP%d' % (name, nparts - 1), '']
    out += doc
    out.append('')
    out += opens
    out.append('')
    out.append(ns)
    out.append('open Refl')
    out.append('')
    out += tail
    io.open(src + '.tmp', 'w', encoding='utf-8').write('\n'.join(out))
    os.replace(src + '.tmp', src)
    print('%s: %d theorems in %d parts of at most %d; preamble %d lines' % (name, len(blocks), nparts, per, len(pre)))

if __name__ == '__main__':
    main()
